import 'package:pdf/pdf.dart';
import 'package:pdf/widgets.dart' as pw;
import 'package:printing/printing.dart';
import 'package:flutter/services.dart';
import 'package:flutter/material.dart';
// import 'package:qr_flutter/qr_flutter.dart';

import '../../settings/services/shop_service.dart';
import '../../../core/utils/pdf_formatters.dart';
import '../../../core/utils/pdf_arabic_helper.dart';

class CustomerStatementPdfService {
  Future<void> generatePdf({
    required BuildContext context,
    required String customer,
    required dynamic balance,
    required List<dynamic> transactions,
  }) async {
    try {
      final shop = await ShopService().getShop();
      final shopName = shop['name']?.toString() ?? '';
      final phone = shop['phone']?.toString() ?? '';
      final address = shop['address']
          .toString()
          .replaceAll('\r\n', ', ')
          .replaceAll('\n', ', ');

      final city = shop['city']?.toString() ?? '';
      final currency = shop['currency'];
      final isArabic = Localizations.localeOf(context).languageCode == 'ar';
      final logoBytes = await rootBundle.load(
        'assets/images/bashsoft_logo.png',
      );
      final arabicFontData = await rootBundle.load(
        'assets/fonts/NotoNaskhArabic-Regular.ttf',
      );

      final logoImage = pw.MemoryImage(logoBytes.buffer.asUint8List());
      final arabicFont = pw.Font.ttf(arabicFontData);

      double totalPurchases = 0;
      double totalPayments = 0;

      final balanceAmount = double.tryParse(balance.toString()) ?? 0;

      final formattedBalance = PdfArabicHelper.display(
        PdfFormatters.currency(balanceAmount, currency, isArabic: isArabic),
        isArabic,
      );

      for (final item in transactions) {
        final amount = double.tryParse(item['amount'].toString()) ?? 0;

        if (item['type'] == 'purchase') {
          totalPurchases += amount;
        } else {
          totalPayments += amount;
        }
      }

      final pdf = pw.Document();

      final statementNumber = 'ST-${DateTime.now().millisecondsSinceEpoch}';

      pdf.addPage(
        pw.MultiPage(
          pageTheme: pw.PageTheme(
            pageFormat: PdfPageFormat.a4,
            theme: pw.ThemeData.withFont(base: arabicFont),
          ),

          header: (context) {
            return pw.Container(
              margin: const pw.EdgeInsets.only(bottom: 5),

              child: pw.Column(
                children: [
                  pw.Image(
                    logoImage,
                    width: 140,
                    height: 60,
                    fit: pw.BoxFit.contain,
                  ),

                  pw.SizedBox(height: 10),

                  pw.Text(
                    shopName,
                    style: pw.TextStyle(
                      fontSize: 22,
                      fontWeight: pw.FontWeight.bold,
                      color: PdfColors.blue900,
                    ),
                  ),

                  pw.Text('$phone | $city | $address'),
                  pw.Text('Currency: $currency'),
                  pw.Divider(),
                ],
              ),
            );
          },

          footer: (context) {
            return pw.Container(
              margin: const pw.EdgeInsets.only(top: 10),

              child: pw.Column(
                children: [
                  pw.Divider(),

                  isArabic
                      ? PdfArabicHelper.rtl(
                          child: pw.Text(
                            PdfArabicHelper.text(
                              'تم الإنشاء بواسطة بش دفتر | $shopName',
                            ),
                            style: pw.TextStyle(
                              font: arabicFont,
                              color: PdfColors.grey,
                            ),
                          ),
                        )
                      : pw.Text(
                          'Generated by BashDafter | $shopName',
                          style: const pw.TextStyle(color: PdfColors.grey),
                        ),

                  pw.Text(
                    'Page ${context.pageNumber} of ${context.pagesCount}',
                    style: const pw.TextStyle(color: PdfColors.grey),
                  ),
                ],
              ),
            );
          },

          build: (context) {
            return [
              pw.Center(
                child: isArabic
                    ? PdfArabicHelper.widget(
                        text: 'كشف حساب العميل',
                        arabicFont: arabicFont,
                        fontSize: 18,
                        fontWeight: pw.FontWeight.bold,
                      )
                    : pw.Text(
                        'Customer Statement',
                        style: pw.TextStyle(
                          fontSize: 18,
                          fontWeight: pw.FontWeight.bold,
                        ),
                      ),
              ),

              pw.SizedBox(height: 30),

              pw.Row(
                mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,

                children: [
                  isArabic
                      ? PdfArabicHelper.rtl(
                          child: pw.RichText(
                            text: pw.TextSpan(
                              children: [
                                pw.TextSpan(
                                  text: PdfArabicHelper.text('العميل: '),
                                  style: pw.TextStyle(
                                    font: arabicFont,
                                    fontWeight: pw.FontWeight.bold,
                                  ),
                                ),

                                pw.TextSpan(
                                  text: customer.toString(),
                                  style: pw.TextStyle(font: arabicFont),
                                ),
                              ],
                            ),
                          ),
                        )
                      : pw.RichText(
                          text: pw.TextSpan(
                            children: [
                              pw.TextSpan(
                                text: 'Customer: ',
                                style: pw.TextStyle(
                                  fontWeight: pw.FontWeight.bold,
                                ),
                              ),

                              pw.TextSpan(text: customer.toString()),
                            ],
                          ),
                        ),

                  pw.Container(
                    padding: const pw.EdgeInsets.symmetric(
                      horizontal: 8,
                      vertical: 4,
                    ),

                    decoration: pw.BoxDecoration(
                      color: PdfColors.blue100,
                      border: pw.Border.all(color: PdfColors.blue700),
                    ),

                    child: pw.Text(
                      'Statement #: $statementNumber',

                      style: pw.TextStyle(
                        color: PdfColors.blue900,
                        fontWeight: pw.FontWeight.bold,
                      ),
                    ),
                  ),
                ],
              ),

              pw.SizedBox(height: 20),

              isArabic
                  ? PdfArabicHelper.rtl(
                      child: pw.RichText(
                        text: pw.TextSpan(
                          children: [
                            pw.TextSpan(
                              text: PdfArabicHelper.text('تاريخ الإنشاء: '),
                              style: pw.TextStyle(
                                font: arabicFont,
                                fontWeight: pw.FontWeight.bold,
                              ),
                            ),

                            pw.TextSpan(
                              text: PdfArabicHelper.display(
                                PdfFormatters.date(
                                  DateTime.now(),
                                  isArabic: true,
                                ),
                                true,
                              ),
                              style: pw.TextStyle(font: arabicFont),
                            ),
                          ],
                        ),
                      ),
                    )
                  : pw.RichText(
                      text: pw.TextSpan(
                        children: [
                          pw.TextSpan(
                            text: 'Generated: ',
                            style: pw.TextStyle(fontWeight: pw.FontWeight.bold),
                          ),

                          pw.TextSpan(text: PdfFormatters.date(DateTime.now())),
                        ],
                      ),
                    ),

              pw.SizedBox(height: 10),

              transactions.isEmpty
                  ? pw.Container(
                      padding: const pw.EdgeInsets.all(10),
                      child: pw.Text(
                        'No transactions available',
                        style: pw.TextStyle(
                          fontStyle: pw.FontStyle.italic,
                          color: PdfColors.grey700,
                        ),
                      ),
                    )
                  : pw.Directionality(
                      textDirection: isArabic
                          ? pw.TextDirection.rtl
                          : pw.TextDirection.ltr,
                      child: pw.Table(
                        border: pw.TableBorder.all(color: PdfColors.grey400),

                        columnWidths: {
                          0: const pw.FlexColumnWidth(2),
                          1: const pw.FlexColumnWidth(2),
                          2: const pw.FlexColumnWidth(2),
                        },

                        children: [
                          // HEADER
                          pw.TableRow(
                            decoration: const pw.BoxDecoration(
                              color: PdfColors.blue200,
                            ),

                            children: [
                              pw.Padding(
                                padding: const pw.EdgeInsets.all(6),
                                child: pw.Text(
                                  isArabic
                                      ? PdfArabicHelper.text('التاريخ')
                                      : 'Date',
                                  textAlign: pw.TextAlign.center,

                                  style: pw.TextStyle(
                                    font: isArabic ? arabicFont : null,
                                    fontWeight: pw.FontWeight.bold,
                                  ),
                                ),
                              ),

                              pw.Padding(
                                padding: const pw.EdgeInsets.all(6),
                                child: pw.Text(
                                  isArabic
                                      ? PdfArabicHelper.text('النوع')
                                      : 'Type',
                                  textAlign: pw.TextAlign.center,

                                  style: pw.TextStyle(
                                    font: isArabic ? arabicFont : null,
                                    fontWeight: pw.FontWeight.bold,
                                  ),
                                ),
                              ),

                              pw.Padding(
                                padding: const pw.EdgeInsets.all(6),
                                child: pw.Text(
                                  isArabic
                                      ? PdfArabicHelper.text('المبلغ')
                                      : 'Amount',
                                  textAlign: pw.TextAlign.center,

                                  style: pw.TextStyle(
                                    font: isArabic ? arabicFont : null,
                                    fontWeight: pw.FontWeight.bold,
                                  ),
                                ),
                              ),
                            ],
                          ),

                          ...transactions.map(
                            (item) => pw.TableRow(
                              children: [
                                pw.Padding(
                                  padding: const pw.EdgeInsets.all(6),
                                  child: pw.Text(
                                    PdfArabicHelper.display(
                                      PdfFormatters.date(
                                        DateTime.parse(item['date'].toString()),
                                        isArabic: isArabic,
                                      ),
                                      isArabic,
                                    ),

                                    textAlign: pw.TextAlign.center,

                                    style: pw.TextStyle(
                                      font: isArabic ? arabicFont : null,
                                    ),
                                  ),
                                ),

                                pw.Padding(
                                  padding: const pw.EdgeInsets.all(6),
                                  child: pw.Text(
                                    item['type'] == 'purchase'
                                        ? (isArabic
                                              ? PdfArabicHelper.text('مشتريات')
                                              : 'PURCHASE')
                                        : (isArabic
                                              ? PdfArabicHelper.text('سداد')
                                              : 'PAYMENT'),

                                    textAlign: pw.TextAlign.center,

                                    style: pw.TextStyle(
                                      font: isArabic ? arabicFont : null,
                                    ),
                                  ),
                                ),

                                pw.Padding(
                                  padding: const pw.EdgeInsets.all(6),
                                  child: pw.Text(
                                    PdfArabicHelper.display(
                                      PdfFormatters.currency(
                                        double.tryParse(
                                              item['amount'].toString(),
                                            ) ??
                                            0,
                                        currency,
                                        isArabic: isArabic,
                                      ),
                                      isArabic,
                                    ),

                                    textAlign: pw.TextAlign.center,

                                    style: pw.TextStyle(
                                      font: isArabic ? arabicFont : null,
                                    ),
                                  ),
                                ),
                              ],
                            ),
                          ),
                        ],
                      ),
                    ),

              pw.SizedBox(height: 10),
              // pw.Text('Total Transactions: ${transactions.length}'),

              isArabic
                  ? PdfArabicHelper.rtl(
                      child: pw.RichText(
                        text: pw.TextSpan(
                          children: [
                            pw.TextSpan(
                              text: PdfArabicHelper.text('إجمالي الحركات: '),
                              style: pw.TextStyle(
                                font: arabicFont,
                                fontWeight: pw.FontWeight.bold,
                              ),
                            ),

                            pw.TextSpan(
                              text: PdfFormatters.number(
                                transactions.length,
                                isArabic: true,
                              ),
                              style: pw.TextStyle(font: arabicFont),
                            ),
                          ],
                        ),
                      ),
                    )
                  : pw.RichText(
                      text: pw.TextSpan(
                        children: [
                          pw.TextSpan(
                            text: 'Total Transactions: ',
                            style: pw.TextStyle(fontWeight: pw.FontWeight.bold),
                          ),

                          pw.TextSpan(
                            text: PdfFormatters.number(transactions.length),
                          ),
                        ],
                      ),
                    ),

              pw.SizedBox(height: 10),

              pw.Container(
                padding: const pw.EdgeInsets.all(6),

                decoration: pw.BoxDecoration(
                  border: pw.Border.all(),
                  color: PdfColors.grey100,
                ),

                child: pw.Column(
                  crossAxisAlignment: pw.CrossAxisAlignment.start,

                  children: [
                    pw.Row(
                      mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,

                      children: [
                        isArabic
                            ? PdfArabicHelper.rtl(
                                child: pw.Text(
                                  PdfArabicHelper.text('إجمالي المشتريات'),
                                  style: pw.TextStyle(
                                    font: arabicFont,
                                    fontWeight: pw.FontWeight.bold,
                                  ),
                                ),
                              )
                            : pw.Text(
                                'Total Purchases',
                                style: pw.TextStyle(
                                  fontWeight: pw.FontWeight.bold,
                                ),
                              ),

                        isArabic
                            ? PdfArabicHelper.rtl(
                                child: pw.Text(
                                  PdfArabicHelper.display(
                                    PdfFormatters.currency(
                                      totalPurchases,
                                      currency,
                                      isArabic: true,
                                    ),
                                    true,
                                  ),
                                  style: pw.TextStyle(font: arabicFont),
                                ),
                              )
                            : pw.Text(
                                PdfFormatters.currency(
                                  totalPurchases,
                                  currency,
                                ),
                              ),
                      ],
                    ),

                    pw.SizedBox(height: 4),

                    pw.Row(
                      mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,

                      children: [
                        isArabic
                            ? PdfArabicHelper.rtl(
                                child: pw.Text(
                                  PdfArabicHelper.text('إجمالي السداد'),
                                  style: pw.TextStyle(
                                    font: arabicFont,
                                    fontWeight: pw.FontWeight.bold,
                                  ),
                                ),
                              )
                            : pw.Text(
                                'Total Payments',
                                style: pw.TextStyle(
                                  fontWeight: pw.FontWeight.bold,
                                ),
                              ),

                        isArabic
                            ? PdfArabicHelper.rtl(
                                child: pw.Text(
                                  PdfArabicHelper.display(
                                    PdfFormatters.currency(
                                      totalPayments,
                                      currency,
                                      isArabic: true,
                                    ),
                                    true,
                                  ),
                                  style: pw.TextStyle(font: arabicFont),
                                ),
                              )
                            : pw.Text(
                                PdfFormatters.currency(totalPayments, currency),
                              ),
                      ],
                    ),

                    pw.Divider(),

                    pw.Row(
                      mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,

                      children: [
                        isArabic
                            ? PdfArabicHelper.rtl(
                                child: pw.Text(
                                  PdfArabicHelper.text('الرصيد'),
                                  style: pw.TextStyle(
                                    font: arabicFont,
                                    fontWeight: pw.FontWeight.bold,
                                  ),
                                ),
                              )
                            : pw.Text(
                                'Balance',
                                style: pw.TextStyle(
                                  fontWeight: pw.FontWeight.bold,
                                ),
                              ),

                        isArabic
                            ? PdfArabicHelper.rtl(
                                child: pw.Text(
                                  formattedBalance,
                                  style: pw.TextStyle(
                                    font: arabicFont,
                                    fontWeight: pw.FontWeight.bold,
                                    color: balanceAmount > 0
                                        ? PdfColors.red800
                                        : PdfColors.green800,
                                  ),
                                ),
                              )
                            : pw.Text(
                                formattedBalance,
                                style: pw.TextStyle(
                                  fontWeight: pw.FontWeight.bold,
                                  color: balanceAmount > 0
                                      ? PdfColors.red800
                                      : PdfColors.green800,
                                ),
                              ),
                      ],
                    ),
                  ],
                ),
              ),

              pw.SizedBox(height: 30),

              pw.Row(
                mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,

                children: [
                  pw.Column(
                    children: [
                      pw.Text('Prepared By'),
                      pw.SizedBox(height: 8),
                      pw.Text('________________'),
                    ],
                  ),

                  pw.Column(
                    children: [
                      pw.Text('Authorized Signature'),
                      pw.SizedBox(height: 8),
                      pw.Text('________________'),
                    ],
                  ),
                ],
              ),
            ];
          },
        ),
      );

      await Printing.layoutPdf(onLayout: (format) async => pdf.save());
    } catch (e) {
      throw Exception('Failed to generate customer statement PDF: $e');
    }
  }
}
