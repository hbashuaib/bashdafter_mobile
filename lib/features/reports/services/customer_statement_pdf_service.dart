import 'package:pdf/pdf.dart';
import 'package:pdf/widgets.dart' as pw;
import 'package:printing/printing.dart';
import 'package:flutter/services.dart';
// import 'package:qr_flutter/qr_flutter.dart';

import '../../settings/services/shop_service.dart';

class CustomerStatementPdfService {
  Future<void> generatePdf({
    required String customer,
    required dynamic balance,
    required List<dynamic> transactions,
  }) async {
    try {
      final shop = await ShopService().getShop();
      final shopName = shop['name']?.toString() ?? '';
      final phone = shop['phone']?.toString() ?? '';
      final address = shop['address']
          .toString()
          .replaceAll('\r\n', ', ')
          .replaceAll('\n', ', ');

      final city = shop['city']?.toString() ?? '';
      final currency = shop['currency'];
      final logoBytes = await rootBundle.load(
        'assets/images/bashsoft_logo.png',
      );

      final logoImage = pw.MemoryImage(logoBytes.buffer.asUint8List());

      double totalPurchases = 0;
      double totalPayments = 0;

      final balanceAmount = double.tryParse(balance.toString()) ?? 0;

      final formattedBalance = balanceAmount.toStringAsFixed(2);

      for (final item in transactions) {
        final amount = double.tryParse(item['amount'].toString()) ?? 0;

        if (item['type'] == 'purchase') {
          totalPurchases += amount;
        } else {
          totalPayments += amount;
        }
      }

      final pdf = pw.Document();

      final statementNumber = 'ST-${DateTime.now().millisecondsSinceEpoch}';

      pdf.addPage(
        pw.MultiPage(
          pageFormat: PdfPageFormat.a4,

          header: (context) {
            return pw.Container(
              margin: const pw.EdgeInsets.only(bottom: 5),

              child: pw.Column(
                children: [
                  pw.Image(
                    logoImage,
                    width: 140,
                    height: 60,
                    fit: pw.BoxFit.contain,
                  ),

                  pw.SizedBox(height: 10),

                  pw.Text(
                    shopName,
                    style: pw.TextStyle(
                      fontSize: 22,
                      fontWeight: pw.FontWeight.bold,
                      color: PdfColors.blue900,
                    ),
                  ),

                  pw.Text('$phone | $city | $address'),
                  pw.Text('Currency: $currency'),
                  pw.Divider(),
                ],
              ),
            );
          },

          footer: (context) {
            return pw.Container(
              margin: const pw.EdgeInsets.only(top: 10),

              child: pw.Column(
                children: [
                  pw.Divider(),

                  pw.Text(
                    'Generated by BashDafter | $shopName',
                    style: const pw.TextStyle(color: PdfColors.grey),
                  ),

                  pw.Text(
                    'Page ${context.pageNumber} of ${context.pagesCount}',
                    style: const pw.TextStyle(color: PdfColors.grey),
                  ),
                ],
              ),
            );
          },

          build: (context) {
            return [
              pw.Center(
                child: pw.Text(
                  'Customer Statement',
                  style: pw.TextStyle(
                    fontSize: 18,
                    fontWeight: pw.FontWeight.bold,
                  ),
                ),
              ),

              pw.SizedBox(height: 30),

              pw.Row(
                mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,

                children: [
                  pw.RichText(
                    text: pw.TextSpan(
                      children: [
                        pw.TextSpan(
                          text: 'Customer: ',
                          style: pw.TextStyle(fontWeight: pw.FontWeight.bold),
                        ),

                        pw.TextSpan(text: customer.toString()),
                      ],
                    ),
                  ),

                  pw.Container(
                    padding: const pw.EdgeInsets.symmetric(
                      horizontal: 8,
                      vertical: 4,
                    ),

                    decoration: pw.BoxDecoration(
                      color: PdfColors.blue100,
                      border: pw.Border.all(color: PdfColors.blue700),
                    ),

                    child: pw.Text(
                      'Statement #: $statementNumber',

                      style: pw.TextStyle(
                        color: PdfColors.blue900,
                        fontWeight: pw.FontWeight.bold,
                      ),
                    ),
                  ),
                ],
              ),

              pw.SizedBox(height: 20),

              pw.RichText(
                text: pw.TextSpan(
                  children: [
                    pw.TextSpan(
                      text: 'Generated: ',
                      style: pw.TextStyle(fontWeight: pw.FontWeight.bold),
                    ),

                    pw.TextSpan(
                      text: DateTime.now().toString().split(' ').first,
                    ),
                  ],
                ),
              ),
              pw.SizedBox(height: 10),

              transactions.isEmpty
                  ? pw.Container(
                      padding: const pw.EdgeInsets.all(10),

                      child: pw.Text(
                        'No transactions available',
                        style: pw.TextStyle(
                          fontStyle: pw.FontStyle.italic,
                          color: PdfColors.grey700,
                        ),
                      ),
                    )
                  : pw.Table.fromTextArray(
                      headerDecoration: const pw.BoxDecoration(
                        color: PdfColors.blue200,
                      ),

                      headerStyle: pw.TextStyle(fontWeight: pw.FontWeight.bold),

                      headerAlignments: {2: pw.Alignment.centerRight},

                      cellAlignments: {2: pw.Alignment.centerRight},

                      headers: const ['Date', 'Type', 'Amount'],

                      data: transactions.map((item) {
                        return [
                          item['date'].toString(),
                          item['type'].toString().toUpperCase(),
                          '${(double.tryParse(item['amount'].toString()) ?? 0).toStringAsFixed(2)} $currency',
                        ];
                      }).toList(),
                    ),

              pw.SizedBox(height: 10),
              // pw.Text('Total Transactions: ${transactions.length}'),

              pw.RichText(
                text: pw.TextSpan(
                  children: [
                    pw.TextSpan(
                      text: 'Total Transactions: ',
                      style: pw.TextStyle(fontWeight: pw.FontWeight.bold),
                    ),

                    pw.TextSpan(text: '${transactions.length}'),
                  ],
                ),
              ),

              pw.SizedBox(height: 10),

              pw.Container(
                padding: const pw.EdgeInsets.all(6),

                decoration: pw.BoxDecoration(
                  border: pw.Border.all(),
                  color: PdfColors.grey100,
                ),

                child: pw.Column(
                  crossAxisAlignment: pw.CrossAxisAlignment.start,

                  children: [
                    pw.Row(
                      mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,

                      children: [
                        pw.Text(
                          'Total Purchases',
                          style: pw.TextStyle(fontWeight: pw.FontWeight.bold),
                        ),

                        pw.Text(
                          '${totalPurchases.toStringAsFixed(2)} $currency',
                        ),
                      ],
                    ),

                    pw.SizedBox(height: 4),

                    pw.Row(
                      mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,

                      children: [
                        pw.Text(
                          'Total Payments',
                          style: pw.TextStyle(fontWeight: pw.FontWeight.bold),
                        ),

                        pw.Text(
                          '${totalPayments.toStringAsFixed(2)} $currency',
                        ),
                      ],
                    ),

                    pw.Divider(),

                    pw.Row(
                      mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,

                      children: [
                        pw.Text(
                          'Balance',
                          style: pw.TextStyle(fontWeight: pw.FontWeight.bold),
                        ),

                        pw.Text(
                          '$formattedBalance $currency',

                          style: pw.TextStyle(
                            fontWeight: pw.FontWeight.bold,
                            color: balanceAmount > 0
                                ? PdfColors.red800
                                : PdfColors.green800,
                          ),
                        ),
                      ],
                    ),
                  ],
                ),
              ),

              pw.SizedBox(height: 30),

              pw.Row(
                mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,

                children: [
                  pw.Column(
                    children: [
                      pw.Text('Prepared By'),
                      pw.SizedBox(height: 8),
                      pw.Text('________________'),
                    ],
                  ),

                  pw.Column(
                    children: [
                      pw.Text('Authorized Signature'),
                      pw.SizedBox(height: 8),
                      pw.Text('________________'),
                    ],
                  ),
                ],
              ),
            ];
          },
        ),
      );

      await Printing.layoutPdf(onLayout: (format) async => pdf.save());
    } catch (e) {
      throw Exception('Failed to generate customer statement PDF: $e');
    }
  }
}
